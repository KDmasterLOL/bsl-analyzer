# Convert PascalCase to snake_case
to_snake_case() {
    echo "$1" | sed -E 's/([A-Z])/_\L\1/g' | sed 's/^_//' | tr -d '\n'
}

for diag in "${java_diagnostics[@]}"; do
    snake_case=$(to_snake_case "$diag")
    rust_file="$RUST_DIAG_DIR/${snake_case}.rs"

    if [ -f "$rust_file" ]; then
        echo "| $diag | \`${snake_case}.rs\` | ✅ **Exists** |"
    else
        echo "| $diag | - | ❌ Missing |"
    fi
done
